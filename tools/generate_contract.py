#!/usr/bin/env python3
"""Compile the pinned App policy into a dependency-free C++ state table."""
import json
import re

from sync_contract import ROOT, verify


def write_generated(name, output):
    destination = ROOT / "build/generated" / name
    destination.parent.mkdir(parents=True, exist_ok=True)
    if not destination.exists() or destination.read_text() != output:
        destination.write_text(output)


def palette():
    css = (ROOT / "contracts/tokens.css").read_text()
    names = {"Background": "background", "Surface": "surface", "SurfaceRaised": "surface-raised",
             "Border": "border", "Foreground": "foreground", "Muted": "muted", "Accent": "accent",
             "AccentForeground": "accent-foreground", "Info": "info", "Good": "good", "Warning": "warning", "Danger": "danger",
             "StateThinking": "state-thinking", "StatePlanning": "state-planning", "StatePacking": "state-packing"}
    lines = ["// Generated from the pinned App dark palette; do not edit.", "#pragma once", "#include <cstdint>", "namespace vibemon::design {"]
    for name, token in names.items():
        values = re.findall(r"--vm-" + re.escape(token) + r"\s*:\s*light-dark\(#[0-9a-fA-F]{6},\s*#([0-9a-fA-F]{6})\)\s*;", css)
        if len(values) != 1:
            raise ValueError("Expected one light-dark hex token: --vm-" + token)
        lines.append("inline constexpr std::uint32_t " + name + " = 0x" + values[0] + ";")
    # Product-card geometry in pixels, as iOS and Android compile it.
    for name, token in {"PanelRadius": "radius-panel", "PanelPadding": "panel-padding"}.items():
        values = re.findall(r"--vm-" + re.escape(token) + r"\s*:\s*(\d+)px\s*;", css)
        if len(values) != 1 or not 0 < int(values[0]) <= 64:
            raise ValueError("Expected one pixel length up to 64px: --vm-" + token)
        lines.append("inline constexpr int " + name + " = " + values[0] + ";")
    # Agent-card motion durations in milliseconds.
    for name in ["orbit", "start", "planning", "packing", "breathe", "danger", "wait", "complete"]:
        values = re.findall(r"--vm-agent-" + name + r"\s*:\s*(\d+)ms\s*;", css)
        if len(values) != 1 or not 0 < int(values[0]) <= 60000:
            raise ValueError("Expected one motion duration up to 60000ms: --vm-agent-" + name)
        lines.append("inline constexpr std::uint32_t Agent" + name.capitalize() + "Ms = " + values[0] + ";")
    return "\n".join([*lines, "}  // namespace vibemon::design", ""])


def generate():
    verify()
    constants = json.loads((ROOT / "contracts/constants.json").read_text())
    policy = json.loads((ROOT / "contracts/monitoring.json").read_text())
    if policy["version"] != 1:
        raise ValueError("Unsupported monitoring policy version")
    lines = ["// Generated by tools/generate_contract.py from the pinned App contract.",
             "#pragma once", "#include <cstdint>", "namespace vibemon::contract {",
             "struct StateRule { const char* id; const char* label; const char* tone; unsigned attentionRank; const char* next; std::uint32_t afterMs; };",
             "inline constexpr std::uint32_t StaleAfterMs = " + str(constants["CLOUD_STALE_MS"]) + ";",
             "inline constexpr std::uint32_t PollIntervalMs = " + str(constants["CLOUD_POLL_MS"]) + ";",
             "inline constexpr StateRule States[] = {"]
    for name, state in policy["states"].items():
        transition = state.get("transition")
        fields = [json.dumps(name), json.dumps(state["label"]), json.dumps(state["tone"]),
                  str(state.get("attentionRank", 0)), json.dumps(transition["state"] if transition else ""),
                  str(constants[transition["after"]] if transition else 0)]
        lines.append("  {" + ", ".join(fields) + "},")
    lines += ["};", "struct UnitPrecision { const char* unit; int fractionDigits; };",
              "inline constexpr UnitPrecision UnitPrecisions[] = {"]
    for unit, digits in policy["measurements"]["unitFractionDigits"].items():
        if not isinstance(digits, int) or isinstance(digits, bool) or not 0 <= digits <= 6:
            raise ValueError("Invalid measurement precision")
        lines.append("  {" + json.dumps(unit) + ", " + str(digits) + "},")
    lines += ["};", "struct MeasurementTone { const char* keyPrefix; double warningFrom; double dangerFrom; };",
              "inline constexpr MeasurementTone MeasurementTones[] = {"]
    for tone in policy["measurements"]["tones"]:
        bounds = [tone["warningFrom"], tone["dangerFrom"]]
        if not isinstance(tone["keyPrefix"], str) or not tone["keyPrefix"] or \
                any(not isinstance(value, (int, float)) or isinstance(value, bool) for value in bounds) or bounds[0] > bounds[1]:
            raise ValueError("Invalid measurement tone")
        lines.append("  {" + json.dumps(tone["keyPrefix"]) + ", " + repr(float(bounds[0])) + ", " + repr(float(bounds[1])) + "},")
    lines += ["};", "struct Provider { const char* id; const char* name; };", "inline constexpr Provider Providers[] = {"]
    for provider in policy["providers"]:
        if not re.fullmatch(r"[a-z][a-z0-9-]{0,31}", provider["id"]) or not isinstance(provider["name"], str) or not provider["name"]:
            raise ValueError("Invalid coding provider")
        lines.append("  {" + json.dumps(provider["id"]) + ", " + json.dumps(provider["name"]) + "},")
    # Touch shows English. Its labels come from the App's shared catalog.
    english = json.loads((ROOT / "contracts/i18n.json").read_text())["en"]
    lines += ["};", "struct Label { const char* key; const char* text; };", "inline constexpr Label Labels[] = {"]
    for key, text in english.items():
        if key.startswith(("metric.", "resource.")) and isinstance(text, str):
            lines.append("  {" + json.dumps(key) + ", " + json.dumps(text) + "},")
    lines += ["};", "}  // namespace vibemon::contract", ""]
    write_generated("monitoring_policy.h", "\n".join(lines))
    write_generated("design_tokens.h", palette())


if __name__ == "__main__":
    generate()
