#!/usr/bin/env python3
"""Compile the pinned App policy into a dependency-free C++ state table."""
import json
import re

from sync_contract import ROOT, verify


def write_generated(name, output):
    destination = ROOT / "build/generated" / name
    destination.parent.mkdir(parents=True, exist_ok=True)
    if not destination.exists() or destination.read_text() != output:
        destination.write_text(output)


def palette():
    css = (ROOT / "contracts/tokens.css").read_text()
    names = {"Background": "background", "Surface": "surface", "SurfaceRaised": "surface-raised",
             "Border": "border", "Foreground": "foreground", "Muted": "muted", "Accent": "accent",
             "AccentForeground": "accent-foreground", "Good": "good", "Warning": "warning", "Danger": "danger"}
    lines = ["// Generated from the pinned App dark palette; do not edit.", "#pragma once", "#include <cstdint>", "namespace vibemon::design {"]
    for name, token in names.items():
        values = re.findall(r"--vm-" + re.escape(token) + r"\s*:\s*light-dark\(#[0-9a-fA-F]{6},\s*#([0-9a-fA-F]{6})\)\s*;", css)
        if len(values) != 1:
            raise ValueError("Expected one light-dark hex token: --vm-" + token)
        lines.append("inline constexpr std::uint32_t " + name + " = 0x" + values[0] + ";")
    return "\n".join([*lines, "}  // namespace vibemon::design", ""])


def generate():
    verify()
    constants = json.loads((ROOT / "contracts/constants.json").read_text())
    policy = json.loads((ROOT / "contracts/monitoring.json").read_text())
    if policy["version"] != 1:
        raise ValueError("Unsupported monitoring policy version")
    lines = ["// Generated by tools/generate_contract.py from the pinned App contract.",
             "#pragma once", "#include <cstdint>", "namespace vibemon::contract {",
             "struct StateRule { const char* id; const char* label; const char* tone; unsigned attentionRank; const char* next; std::uint32_t afterMs; bool holdWhileReporting; };",
             "inline constexpr std::uint32_t StaleAfterMs = " + str(constants["CLOUD_STALE_MS"]) + ";",
             "inline constexpr StateRule States[] = {"]
    for name, state in policy["states"].items():
        transition = state.get("transition")
        fields = [json.dumps(name), json.dumps(state["label"]), json.dumps(state["tone"]),
                  str(state.get("attentionRank", 0)), json.dumps(transition["state"] if transition else ""),
                  str(constants[transition["after"]] if transition else 0),
                  "true" if state.get("holdWhileReporting") else "false"]
        lines.append("  {" + ", ".join(fields) + "},")
    lines += ["};", "struct UnitPrecision { const char* unit; int fractionDigits; };",
              "inline constexpr UnitPrecision UnitPrecisions[] = {"]
    for unit, digits in policy["measurements"]["unitFractionDigits"].items():
        if not isinstance(digits, int) or isinstance(digits, bool) or not 0 <= digits <= 6:
            raise ValueError("Invalid measurement precision")
        lines.append("  {" + json.dumps(unit) + ", " + str(digits) + "},")
    lines += ["};", "}  // namespace vibemon::contract", ""]
    write_generated("monitoring_policy.h", "\n".join(lines))
    write_generated("design_tokens.h", palette())


if __name__ == "__main__":
    generate()
