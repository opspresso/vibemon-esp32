#!/usr/bin/env python3
"""Embed verified product art and the licensed Korean/Latin font in firmware flash."""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent


def array(name, data):
    rows = [", ".join(str(byte) for byte in data[i:i + 32]) for i in range(0, len(data), 32)]
    return "alignas(4) const unsigned char " + name + "[] = {\n" + ",\n".join(rows) + "\n};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "build/generated")
    args = parser.parse_args()
    for record in json.loads((ROOT / "assets/sources.json").read_text()):
        data = (ROOT / "assets" / record["file"]).read_bytes()
        if hashlib.sha256(data).hexdigest() != record["sha256"]:
            raise ValueError("Asset source changed: " + record["file"])
    image = Image.open(ROOT / "assets/vibemon.png").convert("RGBA")
    if image.size != (32, 32):
        raise ValueError("The product mark must be 32 by 32 pixels")
    pixels = bytearray()
    for r, g, b, a in image.get_flattened_data():
        pixels.extend((b, g, r, a))
    output = "// Generated by tools/generate_assets.py; see assets/sources.json for provenance.\n"
    output += array("BrandPixels", pixels)
    output += array("UnicodeFontData", (ROOT / "assets/NanumGothic-Regular.ttf").read_bytes())
    args.output.mkdir(parents=True, exist_ok=True)
    destination = args.output / "assets.inc"
    if not destination.exists() or destination.read_text() != output:
        destination.write_text(output)
    print("Verified and embedded product mark and Unicode font")


if __name__ == "__main__":
    main()
